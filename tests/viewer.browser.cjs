// Run with Playwright installed, or PLAYWRIGHT_MODULE pointing to its package.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  const output = path.resolve('data/validation/viewer');
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({channel:'chrome',headless:true});
  const context = await browser.newContext({viewport:{width:1440,height:960},deviceScaleFactor:1});
  const page = await context.newPage();
  const errors = [];
  const requestedZooms = [];
  const settled = async target => target.waitForFunction(() => activeRaster && !activeRaster.isLoading() && [...document.querySelectorAll('.leaflet-tile-loaded')].every(tile => Number(getComputedStyle(tile).opacity) > .99));
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => {
    const match = request.url().match(/\/tiles\/(\d+)\//);
    if(match) requestedZooms.push(Number(match[1]));
    assert(!request.url().includes('/preview.png'),'The viewer must use full-resolution tiles, not an enlarged preview');
  });
  await page.goto('http://127.0.0.1:8080/viewer', {waitUntil:'networkidle'});
  await page.getByRole('button',{name:'Show HH image',exact:true}).waitFor();
  await page.waitForFunction(() => activeRaster && !activeRaster.isLoading() && document.querySelectorAll('.leaflet-tile-loaded').length > 0);
  assert.equal(await page.locator('#legend').isVisible(),true);
  assert.match(await page.title(),/Image Viewer/);
  assert.equal(await page.locator('#status').getAttribute('data-error'),'false');
  await settled(page);
  await page.screenshot({path:path.join(output,'desktop.png')});
  const initialZoom=await page.evaluate(()=>map.getZoom());
  await page.getByRole('button',{name:'View full detail',exact:true}).click();
  await page.waitForFunction(()=>map.getZoom()===activeLayer.native_zoom&&!activeRaster.isLoading());
  assert(await page.evaluate(()=>map.getZoom())>initialZoom);
  await page.getByRole('button',{name:'Show HV image',exact:true}).click();
  await page.waitForFunction(()=>activeLayer.polarization==='HVHV'&&!activeRaster.isLoading());
  assert.match(await page.locator('#legend-title').textContent(),/HV/);
  await settled(page);
  await page.screenshot({path:path.join(output,'full-detail.png')});
  const before=await page.evaluate(()=>map.getZoom());
  await page.locator('#map').hover();
  await page.mouse.wheel(0,-600);
  await page.waitForFunction(z=>map.getZoom()>z,before);
  await page.waitForFunction(()=>!activeRaster.isLoading());
  await page.waitForFunction(()=>document.getElementById('status').textContent.includes('existing pixels'));
  await page.getByRole('button',{name:'Fit image',exact:true}).click();
  await page.waitForFunction(z=>map.getZoom()<z,before);
  const centerBefore=await page.evaluate(()=>map.getCenter().lng);
  await page.locator('#map').focus();
  await page.keyboard.press('ArrowRight');
  await page.waitForFunction(lng=>map.getCenter().lng!==lng,centerBefore);
  await page.getByRole('button',{name:'World view',exact:true}).click();
  await page.waitForFunction(()=>map.getZoom()===2);
  await page.getByRole('button',{name:'Fit image',exact:true}).click();
  await page.waitForFunction(()=>!activeRaster.isLoading());
  const mobilePage=await context.newPage();
  await mobilePage.setViewportSize({width:390,height:844});
  await mobilePage.goto('http://127.0.0.1:8080/viewer',{waitUntil:'networkidle'});
  await mobilePage.waitForFunction(()=>activeRaster&&!activeRaster.isLoading());
  assert.equal(await mobilePage.locator('#legend').isVisible(),true);
  assert.equal(await mobilePage.getByRole('link',{name:'Download full-resolution image'}).isVisible(),true);
  assert.equal(await mobilePage.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await settled(mobilePage);
  await mobilePage.screenshot({path:path.join(output,'mobile.png')});
  await mobilePage.getByRole('button',{name:'View full detail',exact:true}).click();
  await mobilePage.waitForFunction(()=>map.getZoom()===activeLayer.native_zoom&&!activeRaster.isLoading());
  assert.equal(errors.length,0,errors.join('\n'));
  assert(requestedZooms.some(z=>z>=14));
  fs.writeFileSync(path.join(output,'browser-checks.json'),JSON.stringify({passed:true,errors,initialZoom,requestedZooms:[...new Set(requestedZooms)],checks:['image visible on load','matching legend','full-detail native tiles','HH/HV switching','mouse-wheel zoom','keyboard pan','fit image','world view','mobile layout','no preview PNG enlargement']},null,2));
  console.log('Viewer browser checks passed. Screenshots:',output);
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
